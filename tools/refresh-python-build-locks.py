#!/usr/bin/env python3
"""Explicit maintenance only: regenerate wheel hashes for the declared versions.

CI never calls this command. Review the resulting diff before accepting new inputs.
Runtime versions remain owned by requirements.lock; no version is selected here.
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path
import re
import urllib.request

ROOT = Path(__file__).resolve().parents[1]


def wheel_lock(requirements: list[str]) -> str:
    lines = ["# Generated by tools/refresh-python-build-locks.py --write.",
             "# Only published wheels are allowed; CI must use --require-hashes --only-binary=:all:."]
    for requirement in requirements:
        spec = requirement.split(";", 1)[0].strip()
        if re.fullmatch(r"[A-Za-z0-9_.-]+==[A-Za-z0-9_.+-]+", spec) is None:
            raise ValueError(f"Expected an exact version: {requirement}")
        name, version = spec.split("==")
        with urllib.request.urlopen(f"https://pypi.org/pypi/{name}/{version}/json", timeout=60) as response:
            metadata = json.load(response)
        hashes = sorted({item["digests"]["sha256"] for item in metadata["urls"]
                         if item["packagetype"] == "bdist_wheel" and not item["yanked"]})
        if not hashes:
            raise ValueError(f"No non-yanked wheels for {spec}")
        lines.append(requirement + " \\")
        lines.extend("    --hash=sha256:" + value + (" \\" if index < len(hashes)-1 else "")
                     for index, value in enumerate(hashes))
    return "\n".join(lines) + "\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--write", action="store_true", required=True)
    parser.parse_args()
    lock = json.loads((ROOT / "config/build-environment.lock.json").read_text())
    runtime = [line.strip() for line in (ROOT / "requirements.lock").read_text().splitlines()
               if line.strip() and not line.startswith("#")]
    runtime.append('bleak-winrt==1.2.0; platform_system == "Windows"')
    groups = {"requirements-runtime-build.lock": runtime,
              "requirements-ci.lock": ["PyYAML==6.0.2"],
              "requirements-build.lock": [f"{name}=={version}" for name, version in lock["python_tools"].items()]}
    # Read every remote input before changing any generated file.
    rendered = {name: wheel_lock(items) for name, items in groups.items()}
    for name, content in rendered.items():
        (ROOT / name).write_text(content, encoding="utf-8")


if __name__ == "__main__":
    main()
